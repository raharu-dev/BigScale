// Small row-major 4x4 matrix helpers for the frame-generation camera contract.
//
// Packets carry Unity's column-vector matrices already transposed into row-major row-vector form, so
// every product here is post-multiplying: clip = position * view * projection.
#pragma once

#include <cmath>
#include <cstring>

namespace bigscale
{
struct FgMatrix
{
    float m[4][4]{};

    static FgMatrix Identity()
    {
        FgMatrix out{};
        out.m[0][0] = 1.0f;
        out.m[1][1] = 1.0f;
        out.m[2][2] = 1.0f;
        out.m[3][3] = 1.0f;
        return out;
    }

    static FgMatrix FromArray(const float* values)
    {
        FgMatrix out{};
        if (values != nullptr) std::memcpy(out.m, values, sizeof(out.m));
        return out;
    }

    bool Finite() const
    {
        for (int r = 0; r < 4; r++)
            for (int c = 0; c < 4; c++)
                if (!std::isfinite(m[r][c])) return false;
        return true;
    }
};

inline FgMatrix Mul(const FgMatrix& a, const FgMatrix& b)
{
    FgMatrix out{};
    for (int r = 0; r < 4; r++)
        for (int c = 0; c < 4; c++)
        {
            float sum = 0.0f;
            for (int k = 0; k < 4; k++) sum += a.m[r][k] * b.m[k][c];
            out.m[r][c] = sum;
        }
    return out;
}

// General inverse by cofactor expansion. Returns identity and false for a singular matrix so the
// caller can suspend instead of feeding the SDK a fabricated transform.
inline bool Inverse(const FgMatrix& in, FgMatrix& out)
{
    const float* a = &in.m[0][0];
    float inv[16];
    inv[0] = a[5] * a[10] * a[15] - a[5] * a[11] * a[14] - a[9] * a[6] * a[15] + a[9] * a[7] * a[14] +
        a[13] * a[6] * a[11] - a[13] * a[7] * a[10];
    inv[4] = -a[4] * a[10] * a[15] + a[4] * a[11] * a[14] + a[8] * a[6] * a[15] - a[8] * a[7] * a[14] -
        a[12] * a[6] * a[11] + a[12] * a[7] * a[10];
    inv[8] = a[4] * a[9] * a[15] - a[4] * a[11] * a[13] - a[8] * a[5] * a[15] + a[8] * a[7] * a[13] +
        a[12] * a[5] * a[11] - a[12] * a[7] * a[9];
    inv[12] = -a[4] * a[9] * a[14] + a[4] * a[10] * a[13] + a[8] * a[5] * a[14] - a[8] * a[6] * a[13] -
        a[12] * a[5] * a[10] + a[12] * a[6] * a[9];
    inv[1] = -a[1] * a[10] * a[15] + a[1] * a[11] * a[14] + a[9] * a[2] * a[15] - a[9] * a[3] * a[14] -
        a[13] * a[2] * a[11] + a[13] * a[3] * a[10];
    inv[5] = a[0] * a[10] * a[15] - a[0] * a[11] * a[14] - a[8] * a[2] * a[15] + a[8] * a[3] * a[14] +
        a[12] * a[2] * a[11] - a[12] * a[3] * a[10];
    inv[9] = -a[0] * a[9] * a[15] + a[0] * a[11] * a[13] + a[8] * a[1] * a[15] - a[8] * a[3] * a[13] -
        a[12] * a[1] * a[11] + a[12] * a[3] * a[9];
    inv[13] = a[0] * a[9] * a[14] - a[0] * a[10] * a[13] - a[8] * a[1] * a[14] + a[8] * a[2] * a[13] +
        a[12] * a[1] * a[10] - a[12] * a[2] * a[9];
    inv[2] = a[1] * a[6] * a[15] - a[1] * a[7] * a[14] - a[5] * a[2] * a[15] + a[5] * a[3] * a[14] +
        a[13] * a[2] * a[7] - a[13] * a[3] * a[6];
    inv[6] = -a[0] * a[6] * a[15] + a[0] * a[7] * a[14] + a[4] * a[2] * a[15] - a[4] * a[3] * a[14] -
        a[12] * a[2] * a[7] + a[12] * a[3] * a[6];
    inv[10] = a[0] * a[5] * a[15] - a[0] * a[7] * a[13] - a[4] * a[1] * a[15] + a[4] * a[3] * a[13] +
        a[12] * a[1] * a[7] - a[12] * a[3] * a[5];
    inv[14] = -a[0] * a[5] * a[14] + a[0] * a[6] * a[13] + a[4] * a[1] * a[14] - a[4] * a[2] * a[13] -
        a[12] * a[1] * a[6] + a[12] * a[2] * a[5];
    inv[3] = -a[1] * a[6] * a[11] + a[1] * a[7] * a[10] + a[5] * a[2] * a[11] - a[5] * a[3] * a[10] -
        a[9] * a[2] * a[7] + a[9] * a[3] * a[6];
    inv[7] = a[0] * a[6] * a[11] - a[0] * a[7] * a[10] - a[4] * a[2] * a[11] + a[4] * a[3] * a[10] +
        a[8] * a[2] * a[7] - a[8] * a[3] * a[6];
    inv[11] = -a[0] * a[5] * a[11] + a[0] * a[7] * a[9] + a[4] * a[1] * a[11] - a[4] * a[3] * a[9] -
        a[8] * a[1] * a[7] + a[8] * a[3] * a[5];
    inv[15] = a[0] * a[5] * a[10] - a[0] * a[6] * a[9] - a[4] * a[1] * a[10] + a[4] * a[2] * a[9] +
        a[8] * a[1] * a[6] - a[8] * a[2] * a[5];

    const float determinant = a[0] * inv[0] + a[1] * inv[4] + a[2] * inv[8] + a[3] * inv[12];
    if (!std::isfinite(determinant) || std::fabs(determinant) < 1e-12f) return false;
    const float scale = 1.0f / determinant;
    for (int i = 0; i < 16; i++) (&out.m[0][0])[i] = inv[i] * scale;
    return out.Finite();
}
}
